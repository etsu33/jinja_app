from django.core.management.base import BaseCommand
from django.db import connection

SQL = """
CREATE TABLE IF NOT EXISTS temples_featureusage (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope varchar(16) NOT NULL,
    anon_id varchar(64) NOT NULL DEFAULT '',
    feature varchar(32) NOT NULL,
    count integer NOT NULL DEFAULT 0 CHECK (count >= 0),
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    updated_at timestamp with time zone NOT NULL DEFAULT NOW(),
    user_id bigint NULL REFERENCES users_user(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT chk_feature_usage_scope_target CHECK (
        (scope = 'user' AND user_id IS NOT NULL AND anon_id = '')
        OR
        (scope = 'anonymous' AND user_id IS NULL AND anon_id > '')
    )
);
"""

class Command(BaseCommand):
    help = "Create temples_featureusage table if it is missing."

    def handle(self, *args, **options):
        with connection.cursor() as cursor:
            cursor.execute(SQL)
            cursor.execute("SELECT to_regclass('public.temples_featureusage');")
            table = cursor.fetchone()[0]
        self.stdout.write(self.style.SUCCESS(f"temples_featureusage repair result: {table}"))
