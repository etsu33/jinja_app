from __future__ import annotations

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand
from django.db import connection


def _description_column_names(description):
    return {column.name for column in description}


class Command(BaseCommand):
    help = "Create temples_featureusage table and repair required shrine columns if missing."

    def handle(self, *args, **options):
        auth_app_label, auth_model_name = settings.AUTH_USER_MODEL.split(".", 1)
        user_model = apps.get_model(auth_app_label, auth_model_name)
        user_table = connection.ops.quote_name(user_model._meta.db_table)

        if connection.vendor == "sqlite":
            sql_statements = [
                """
                CREATE TABLE IF NOT EXISTS temples_featureusage (
                    id integer PRIMARY KEY AUTOINCREMENT,
                    scope varchar(16) NOT NULL,
                    anon_id varchar(64) NOT NULL DEFAULT '',
                    feature varchar(32) NOT NULL,
                    count integer NOT NULL DEFAULT 0 CHECK (count >= 0),
                    created_at datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    user_id integer NULL REFERENCES {user_table}(id),
                    CONSTRAINT chk_feature_usage_scope_target CHECK (
                        (scope = 'user' AND user_id IS NOT NULL AND anon_id = '')
                        OR
                        (scope = 'anonymous' AND user_id IS NULL AND anon_id > '')
                    )
                )
                """.format(user_table=user_table),
                "CREATE INDEX IF NOT EXISTS temples_fea_scope_16bb7d_idx ON temples_featureusage (scope, feature)",
                "CREATE INDEX IF NOT EXISTS temples_fea_user_id_ed3ce9_idx ON temples_featureusage (user_id, feature)",
                "CREATE INDEX IF NOT EXISTS temples_fea_anon_id_6f0176_idx ON temples_featureusage (anon_id, feature)",
                "CREATE UNIQUE INDEX IF NOT EXISTS uq_feature_usage_user_feature ON temples_featureusage (user_id, feature) WHERE scope = 'user' AND user_id IS NOT NULL",
                "CREATE UNIQUE INDEX IF NOT EXISTS uq_feature_usage_anon_feature ON temples_featureusage (anon_id, feature) WHERE scope = 'anonymous' AND anon_id > ''",
            ]
            existence_sql = "SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'temples_featureusage'"
        else:
            sql_statements = [
                f"""
                CREATE TABLE IF NOT EXISTS temples_featureusage (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    scope varchar(16) NOT NULL,
                    anon_id varchar(64) NOT NULL DEFAULT '',
                    feature varchar(32) NOT NULL,
                    count integer NOT NULL DEFAULT 0 CHECK (count >= 0),
                    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
                    updated_at timestamp with time zone NOT NULL DEFAULT NOW(),
                    user_id bigint NULL REFERENCES {user_table}(id) DEFERRABLE INITIALLY DEFERRED,
                    CONSTRAINT chk_feature_usage_scope_target CHECK (
                        (scope = 'user' AND user_id IS NOT NULL AND anon_id = '')
                        OR
                        (scope = 'anonymous' AND user_id IS NULL AND anon_id > '')
                    )
                )
                """,
                "CREATE INDEX IF NOT EXISTS temples_fea_scope_16bb7d_idx ON temples_featureusage (scope, feature)",
                "CREATE INDEX IF NOT EXISTS temples_fea_user_id_ed3ce9_idx ON temples_featureusage (user_id, feature)",
                "CREATE INDEX IF NOT EXISTS temples_fea_anon_id_6f0176_idx ON temples_featureusage (anon_id, feature)",
                "CREATE UNIQUE INDEX IF NOT EXISTS uq_feature_usage_user_feature ON temples_featureusage (user_id, feature) WHERE scope = 'user' AND user_id IS NOT NULL",
                "CREATE UNIQUE INDEX IF NOT EXISTS uq_feature_usage_anon_feature ON temples_featureusage (anon_id, feature) WHERE scope = 'anonymous' AND anon_id > ''",
            ]
            existence_sql = "SELECT to_regclass('public.temples_featureusage')"

        with connection.cursor() as cursor:
            for statement in sql_statements:
                cursor.execute(statement)

            shrine_columns = _description_column_names(
                connection.introspection.get_table_description(cursor, "temples_shrine")
            )
            if "visit_style_tags" not in shrine_columns:
                if connection.vendor == "sqlite":
                    cursor.execute(
                        "ALTER TABLE temples_shrine "
                        "ADD COLUMN visit_style_tags text NOT NULL DEFAULT '[]'"
                    )
                else:
                    cursor.execute(
                        "ALTER TABLE temples_shrine "
                        "ADD COLUMN visit_style_tags jsonb NOT NULL DEFAULT '[]'::jsonb"
                    )

            cursor.execute(existence_sql)
            table = cursor.fetchone()[0]

        self.stdout.write(self.style.SUCCESS(f"temples_featureusage repair result: {table}"))
