from __future__ import annotations

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand
from django.db import connection


class Command(BaseCommand):
    help = "Create temples_favorite table if missing."

    def handle(self, *args, **options):
        auth_app_label, auth_model_name = settings.AUTH_USER_MODEL.split(".", 1)
        user_model = apps.get_model(auth_app_label, auth_model_name)
        user_table = connection.ops.quote_name(user_model._meta.db_table)

        shrine_model = apps.get_model("temples", "Shrine")
        shrine_table = connection.ops.quote_name(shrine_model._meta.db_table)

        if connection.vendor == "sqlite":
            sql_statements = [
                f"""
                CREATE TABLE IF NOT EXISTS temples_favorite (
                    id integer PRIMARY KEY AUTOINCREMENT,
                    user_id integer NOT NULL REFERENCES {user_table}(id),
                    shrine_id bigint NULL REFERENCES {shrine_table}(id),
                    place_id varchar(128) NULL,
                    created_at datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT chk_favorite_exactly_one_target CHECK (
                        (shrine_id IS NOT NULL AND place_id IS NULL)
                        OR
                        (shrine_id IS NULL AND place_id IS NOT NULL)
                    )
                )
                """,
                "CREATE UNIQUE INDEX IF NOT EXISTS uniq_favorite_user_shrine ON temples_favorite (user_id, shrine_id) WHERE shrine_id IS NOT NULL",
                "CREATE UNIQUE INDEX IF NOT EXISTS uniq_favorite_user_place ON temples_favorite (user_id, place_id) WHERE place_id IS NOT NULL",
                "CREATE INDEX IF NOT EXISTS temples_favorite_place_id_idx ON temples_favorite (place_id)",
                "CREATE INDEX IF NOT EXISTS idx_fav_user_created ON temples_favorite (user_id, created_at)",
            ]
            existence_sql = "SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'temples_favorite'"
        else:
            sql_statements = [
                f"""
                CREATE TABLE IF NOT EXISTS temples_favorite (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id integer NOT NULL REFERENCES {user_table}(id) DEFERRABLE INITIALLY DEFERRED,
                    shrine_id bigint NULL REFERENCES {shrine_table}(id) DEFERRABLE INITIALLY DEFERRED,
                    place_id varchar(128) NULL,
                    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
                    CONSTRAINT chk_favorite_exactly_one_target CHECK (
                        (shrine_id IS NOT NULL AND place_id IS NULL)
                        OR
                        (shrine_id IS NULL AND place_id IS NOT NULL)
                    )
                )
                """,
                "CREATE UNIQUE INDEX IF NOT EXISTS uniq_favorite_user_shrine ON temples_favorite (user_id, shrine_id) WHERE shrine_id IS NOT NULL",
                "CREATE UNIQUE INDEX IF NOT EXISTS uniq_favorite_user_place ON temples_favorite (user_id, place_id) WHERE place_id IS NOT NULL",
                "CREATE INDEX IF NOT EXISTS temples_favorite_place_id_idx ON temples_favorite (place_id)",
                "CREATE INDEX IF NOT EXISTS idx_fav_user_created ON temples_favorite (user_id, created_at)",
            ]
            existence_sql = "SELECT to_regclass('public.temples_favorite')"

        with connection.cursor() as cursor:
            for statement in sql_statements:
                cursor.execute(statement)

            cursor.execute(existence_sql)
            table = cursor.fetchone()[0]

        self.stdout.write(self.style.SUCCESS(f"temples_favorite repair result: {table}"))
